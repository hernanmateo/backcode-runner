// Idioma del runner (terminal, actividad y errores que ve la app). Antes de iniciar sesión, el del sistema; después,
// el del perfil del usuario en la app (users/{uid}.lang), en vivo. BACKCODE_LANG manda sobre todo.
import { IS_BINARY } from "./paths.js";


export type Lang = "es" | "en" | "ca";

const isLang = (v: unknown): v is Lang => v === "es" || v === "en" || v === "ca";

/** Idioma del sistema (LC_ALL / LANG); si no es uno de los nuestros, inglés. */
export function systemLang(): Lang {
  const l = (process.env.LC_ALL || process.env.LANG || "").toLowerCase();
  return l.startsWith("es") ? "es" : l.startsWith("ca") ? "ca" : "en";
}

let override: Lang | undefined = isLang(process.env.BACKCODE_LANG) ? process.env.BACKCODE_LANG : undefined;
let profile: Lang | undefined;

/** Idioma del perfil (lo que no sea es/en/ca se ignora y vuelve al del sistema). */
export function setLang(l: unknown): void {
  profile = isLang(l) ? l : undefined;
}
/** BACKCODE_LANG del .env (el del entorno ya se leyó al cargar el módulo). */
export function setLangOverride(l: unknown): void {
  if (isLang(l)) override = l;
}
export const lang = (): Lang => override ?? profile ?? systemLang();

