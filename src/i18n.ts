/** Textos de la página del panel (claves ui.*, sin el prefijo) en el idioma actual. */
export function panelStrings(): Record<string, string> {
  return Object.fromEntries(Object.entries(STRINGS[lang()]).filter(([k]) => k.startsWith("ui.")).map(([k, v]) => [k.slice(3), command(v)]));
}

/** Texto en el idioma actual con {marcadores} sustituidos. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const text = command(STRINGS[lang()][key]);
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}
